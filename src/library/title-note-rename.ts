// The vault side of renaming a book: point its title note at the file where it now is.
//
// The twin of title-note-delete.ts, and it matches the same way — textually, through `linkNamesFile` — because at
// rename time the old path has already left the vault, so no link to it resolves.

import type { App, TFile } from 'obsidian';
import { vaultCandidates } from './candidates';
import { linkTarget, parseRecord, toStringList } from './record';
import { ORBIS_REGION_END, ORBIS_REGION_START, recordLinkText } from './record-note';
import { linkNamesFile } from './title-note-cleanup';

/**
 * Rewrite every link to `oldPath` in a title note that Orbis owns: the `files` entries, and the embed inside Orbis's
 * own region of the body. Returns how many title notes changed.
 *
 * **Not left to Obsidian.** Renaming a file asks whether to update links to it, and the answer is anyone's guess —
 * with No, `files` kept naming the old file. The Library reads `files` to know which book a note is for, so a stale
 * entry left the note pointing at nothing. Both are Orbis's own: `files` is machine-read, and the region between the markers is
 * regenerated by Orbis. Text outside the region is the reader's, so it is left to Obsidian's answer.
 *
 * Already-updated links name the new file, not the old one, so a rename Obsidian handled changes nothing here.
 */
export async function relinkTitleNotes(app: App, oldPath: string, book: TFile): Promise<number> {
  const link = `[[${recordLinkText(book)}]]`;
  let changed = 0;
  for (const candidate of vaultCandidates(app)) {
    const record = parseRecord(candidate.path, candidate.frontmatter);
    if (!record) continue;
    const note = app.vault.getFileByPath(candidate.path);
    if (!note) continue;
    const exists = (path: string) => app.vault.getFileByPath(path) !== null;
    const names = (value: string) => linkNamesFile(linkTarget(value), oldPath, note.path, exists);
    let touched = false;
    if (record.files.some(names)) {
      await app.fileManager.processFrontMatter(note, (fm: Record<string, unknown>) => {
        fm.files = toStringList(fm.files).map((value) => (names(value) ? link : value));
      });
      touched = true;
    }
    // Read first and write only on a real change: every title note is a candidate, and a rename must not rewrite —
    // and so re-sync — the whole library.
    const relink = (content: string) =>
      relinkOwnedRegion(content, (target) => linkNamesFile(target, oldPath, note.path, exists), recordLinkText(book));
    const cached = await app.vault.cachedRead(note);
    if (relink(cached) !== cached) {
      await app.vault.process(note, relink);
      touched = true;
    }
    if (touched) changed++;
  }
  return changed;
}

/** Re-point the wikilinks and embeds inside Orbis's own region whose target `names` says is the old file. */
export function relinkOwnedRegion(content: string, names: (target: string) => boolean, newTarget: string): string {
  const start = content.indexOf(ORBIS_REGION_START);
  if (start === -1) return content;
  const endMarker = content.indexOf(ORBIS_REGION_END, start);
  const end = endMarker === -1 ? content.length : endMarker;
  const region = content
    .slice(start, end)
    .replace(/(!?)\[\[([^\]|#]+)([^\]]*)\]\]/g, (whole, bang, target, rest) =>
      names(String(target).trim()) ? `${bang}[[${newTarget}${rest}]]` : whole
    );
  return content.slice(0, start) + region + content.slice(end);
}
